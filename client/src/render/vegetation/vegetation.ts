/**
 * Vegetation renderer (M0-024): grass tufts, shrubs and trees from per-chunk instance tables.
 *
 * Per 64 m chunk and species there is one `LodBuckets` (thin-instance matrix buffers, one per LOD) and one Babylon mesh
 * per LOD, so a chunk costs at most one draw call per species and LOD (§9.6). Meshes are clones of one master mesh per
 * (species, LOD) that share geometry and material; materials are shared per species, so the whole system has 5
 * foliage/impostor materials and 2 bake materials regardless of chunk count.
 *
 * Everything is placeholder: geometry and colours are generated by placeholder-meshes.ts (names `PH_V-NAT-002` trees,
 * `PH_V-NAT-004` grass/shrubs, ASSET_GAPS §3). The interface towards map data is the instance table bytes
 * (scatter.ts), so M1-035/M1-051 swap the source of tables and meshes without touching this class' API.
 */
