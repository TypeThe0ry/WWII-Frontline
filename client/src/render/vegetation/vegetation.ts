export interface HeightSource {
  heightAt(x: number, z: number): number;
}

export interface ChunkTable {
  cx: number;
  cz: number;
  /** `INSTANCE_BYTES` per entry, see scatter.ts. */
  bytes: Uint8Array;
}

export interface VegetationOptions {
  kind: 'webgpu' | 'webgl2';
  quality?: QualityTier;
  /** Bake the impostor atlases (default true). Off in headless unit tests without a GPU. */
  bake?: boolean;
  /** Pixels per atlas view: 128 = full 1536 atlas, 64 = `?impostor=lowres`. */
  cellPx?: number;
  wind?: WindState;
  /** CPU budget for LOD re-bucketing per frame (ms); buckets over budget are served next frame. Infinity = unbounded. */
  rebucketBudgetMs?: number;
  /**
   * Draw-call grouping: the instance tables stay 64 m chunks, but `groupChunks` x `groupChunks` chunks share one set of
   * LOD meshes (default 1 = one per chunk). Babylon's per-draw CPU cost dominates on a fast GPU, and bigger groups cut the
   * number of draws and meshes (M1-069b: 400-800 draws -> ~100) at the price of coarser frustum culling.
   */
  groupChunks?: number;
}

export interface VegetationStats {
  /** Instance table sizes. */
  total: { grass: number; shrub: number; tree: number };
  /** Instances currently assigned to each LOD, per species key (last entry of tree/shrub = impostor). */
  perLod: { grass: number[]; shrub: number[]; tree: number[] };
  /** Instances actually drawn (in meshes that passed frustum culling) / their draw calls / triangles; refreshed by `perfStats`. */
  drawn: { instances: number; drawCalls: number; tris: number };
  /** Bucket classification time of the last `update`, ms, and its window statistics. */
  rebucketMs: number;
  /** Part of `rebucketMs` spent uploading changed matrices (WebGL/WebGPU buffer writes) and the pure CPU classification part. */
  uploadMs: number;
  classifyMs: number;
  rebucket: WindowStats;
  /** Window statistics of the classification-only time (the "CPU bucketing cost" of M0-024 acceptance 6). */
  classify: WindowStats;
  /** Buckets postponed by the budget in the last update. */
  deferred: number;
  /** Instances moved between LODs in the last update. */
  moved: number;
  /** Impostor bake wall time (ms, 0 = not baked) and atlas size. */
  bakeMs: number;
  atlasPx: number;
  /** CPU-side bytes of the instance buffers and impostor atlases (GPU copies are the same order). */
  bufferBytes: number;
  atlasBytes: number;
}

interface SpeciesGfx {
  info: SpeciesInfo;
  /** Mesh LOD masters (index = LOD) and, for shrub/tree, the impostor quad master as the last entry. */
  masters: Mesh[];
  /** Materials matching `masters` (impostor last). */
  materials: ShaderMaterial[];
  bounds: MeshBounds;
  tris: number[];
}

interface Bucket {
  species: number;
  cx: number;
  cz: number;
  buckets: LodBuckets;
  meshes: Mesh[];
}

const QUAD_TRIS = 2;

function foliageMaterial(scene: Scene, name: string, wgsl: boolean, up: number, fade: [number, number]): ShaderMaterial {
  const m = new ShaderMaterial(
    name,
    scene,
    wgsl ? { vertexSource: FOLIAGE_VERTEX_WGSL, fragmentSource: FOLIAGE_FRAGMENT_WGSL } : { vertexSource: FOLIAGE_VERTEX_GLSL, fragmentSource: FOLIAGE_FRAGMENT_GLSL },
    {
      attributes: ['position', 'normal', 'color'],
      uniforms: ['viewProjection', 'uCam', 'uWind', 'uFade', 'uParams'],
      shaderLanguage: wgsl ? ShaderLanguage.WGSL : ShaderLanguage.GLSL,
    },
  );
  m.backFaceCulling = false;
  m.setVector3('uCam', new Vector3());
  m.setVector4('uWind', new Vector4(1, 0, 0, 0));
  m.setVector2('uFade', new Vector2(fade[0], fade[1]));
  m.setVector2('uParams', new Vector2(up, SWAY_OMEGA));
  return m;
}

function impostorMaterial(scene: Scene, name: string, wgsl: boolean, bounds: MeshBounds, flipV: boolean): ShaderMaterial {
  const m = new ShaderMaterial(
    name,
    scene,
    wgsl ? { vertexSource: IMPOSTOR_VERTEX_WGSL, fragmentSource: IMPOSTOR_FRAGMENT_WGSL } : { vertexSource: IMPOSTOR_VERTEX_GLSL, fragmentSource: IMPOSTOR_FRAGMENT_GLSL },
    {
      attributes: ['position'],
      uniforms: ['viewProjection', 'uCam', 'uImp'],
      samplers: ['uAtlasA', 'uAtlasN'],
      shaderLanguage: wgsl ? ShaderLanguage.WGSL : ShaderLanguage.GLSL,
    },
  );
  m.backFaceCulling = false;
  m.setVector3('uCam', new Vector3());
  m.setVector4('uImp', new Vector4(bounds.radius, bounds.centerY, ATLAS_CELLS, flipV ? 1 : 0));
  return m;
}

function meshFrom(scene: Scene, name: string, d: MeshData): Mesh {
  const m = new Mesh(name, scene);
  const vd = new VertexData();
  vd.positions = d.positions;
  vd.normals = d.normals;
  vd.colors = d.colors;
  vd.indices = d.indices;
  vd.applyToMesh(m, false);
  m.isPickable = false;
  m.setEnabled(false);
  return m;
}

function quadMesh(scene: Scene, name: string): Mesh {
  const m = new Mesh(name, scene);
  const vd = new VertexData();
  vd.positions = new Float32Array([-1, -1, 0, 1, -1, 0, 1, 1, 0, -1, 1, 0]);
  vd.indices = new Uint16Array([0, 1, 2, 0, 2, 3]);
  vd.applyToMesh(m, false);
  m.isPickable = false;
  m.setEnabled(false);
  return m;
}

export class Vegetation {
  readonly scene: Scene;
  readonly stats: VegetationStats;
  readonly atlases: Map<string, ImpostorAtlas> = new Map();
  /** All vegetation meshes (masters excluded), for tests and stats. */
  readonly meshes: Mesh[] = [];
  private readonly gfx: SpeciesGfx[] = [];
  private readonly materials: ShaderMaterial[] = [];
  private readonly buckets: Bucket[] = [];
  private readonly wgsl: boolean;
  private readonly wind: WindState;
  private readonly windPeriod = (Math.PI * 2 * 100) / SWAY_OMEGA;
  private readonly windVec = new Vector4();
  private readonly camVec = new Vector3();
  private readonly rebucketStats = new RingStats(2048);
  private readonly classifyStats = new RingStats(2048);
  private quality: QualityM0;
  private thr2: number[][] = [];
  private thrVersion = 0;
  private budgetMs: number;
  private rotate = 0;
  private lastStatsAt = 0;
  private isolated = false;
  private probes: Mesh[] = [];
  private trisOf: Map<Mesh, number> | null = null;

  private constructor(scene: Scene, readonly opts: VegetationOptions) {
    this.scene = scene;
    this.wgsl = opts.kind === 'webgpu';
    this.wind = opts.wind ?? defaultWind();
    this.quality = QUALITY_M0[opts.quality ?? 'high'];
    this.refreshThresholds();
    this.budgetMs = opts.rebucketBudgetMs ?? 0.45;
    this.stats = {
      total: { grass: 0, shrub: 0, tree: 0 },
      perLod: { grass: [0, 0], shrub: [0, 0, 0], tree: [0, 0, 0] },
      drawn: { instances: 0, drawCalls: 0, tris: 0 },
      rebucketMs: 0,
      uploadMs: 0,
      classifyMs: 0,
      classify: { count: 0, mean: 0, p50: 0, p99: 0, max: 0 },
      rebucket: { count: 0, mean: 0, p50: 0, p99: 0, max: 0 },
      deferred: 0,
      moved: 0,
      bakeMs: 0,
      atlasPx: 0,
      bufferBytes: 0,
      atlasBytes: 0,
    };
  }

  /** Scatter instance tables for every chunk of a `sizeM` square block (M0 runtime scatter; M1 bakes them offline). */
  static scatterTables(
    sizeM: number,
    seed: number,
    height: HeightSource,
    exclusions: readonly ScatterPoint[] = [],
    extra: Pick<ScatterInput, 'mask' | 'grassScale'> = {},
  ): ChunkTable[] {
    const n = Math.ceil(sizeM / CHUNK_SIZE_M);
    const out: ChunkTable[] = [];
    for (let cz = 0; cz < n; cz++) {
      for (let cx = 0; cx < n; cx++) {
        out.push({ cx, cz, bytes: scatterChunk({ chunkX: cx, chunkZ: cz, seed, heightAt: (x, z) => height.heightAt(x, z), exclusions, ...extra }) });
      }
    }
    return out;
  }

  static async create(scene: Scene, height: HeightSource, tables: readonly ChunkTable[], opts: VegetationOptions): Promise<Vegetation> {
    const v = new Vegetation(scene, opts);
    v.buildGfx();
    if (opts.bake !== false) await v.bakeAtlases(opts.cellPx ?? CELL_PX);
    v.buildChunks(height, tables);
    return v;
  }

  // ---------------------------------------------------------------- setup

  private buildGfx(): void {
    const scene = this.scene;
    const wgsl = this.wgsl;
    const q = this.quality;
    const grassFade: [number, number] = [q.grassDistance * 0.75, q.grassDistance];
    const make = (info: SpeciesInfo, builders: ((lod: 0 | 1) => MeshData)[], matName: string, up: number, fade: [number, number], withImpostor: boolean): SpeciesGfx => {
      const meshes = builders.map((b, lod) => b(lod as 0 | 1));
      const names = ['lod0', 'lod1'];
      const bounds = boundsOf(meshes[0]!);
      const masters = meshes.map((d, lod) => meshFrom(scene, `PH_${info.reqId}__master_${info.key}_${names[lod]}`, d));
      const mat = foliageMaterial(scene, matName, wgsl, up, fade);
      const materials = masters.map(() => mat);
      masters.forEach((m) => (m.material = mat));
      const tris = meshes.map((d) => d.triangles);
      this.materials.push(mat);
      if (withImpostor) {
        // flipV = false on both backends: Babylon renders into render targets with GL-consistent orientation on WebGPU too
        // (measured: flipV = true gave a vertically mirrored impostor, IoU 0.3 vs the mesh, see vegetation.spec.ts).
        const imat = impostorMaterial(scene, `${matName}${matName.includes('__') ? '_' : '__'}impostor`, wgsl, bounds, false);
        const qm = quadMesh(scene, `PH_${info.reqId}__master_${info.key}_impostor`);
        qm.material = imat;
        masters.push(qm);
        materials.push(imat);
        tris.push(QUAD_TRIS);
        this.materials.push(imat);
      }
      return { info, masters, materials, bounds, tris };
    };
    this.gfx[SPECIES_GRASS] = make(SPECIES[SPECIES_GRASS]!, [buildGrass, buildGrass], 'PH_V-NAT-004', 0.65, grassFade, false);
    this.gfx[SPECIES_SHRUB] = make(SPECIES[SPECIES_SHRUB]!, [buildShrub, buildShrub], 'PH_V-NAT-004__shrub', 0.3, [0, 0], true);
    this.gfx[SPECIES_TREE] = make(SPECIES[SPECIES_TREE]!, [buildTree, buildTree], 'PH_V-NAT-002', 0.15, [0, 0], true);
  }

  private async bakeAtlases(cellPx: number): Promise<void> {
    let ms = 0;
    let bytes = 0;
    for (const sp of [SPECIES_SHRUB, SPECIES_TREE]) {
      const g = this.gfx[sp]!;
      const mesh0 = sp === SPECIES_TREE ? buildTree(0) : buildShrub(0);
      const atlas = await bakeImpostorAtlas(this.scene.getEngine(), mesh0, g.bounds, {
        reqId: g.info.reqId,
        kind: this.opts.kind,
        cellPx,
        clear: sp === SPECIES_TREE ? [0.2, 0.36, 0.13] : [0.24, 0.4, 0.14],
      });
      this.atlases.set(g.info.key, atlas);
      const imat = g.materials[g.materials.length - 1]!;
      imat.setTexture('uAtlasA', atlas.albedo);
      imat.setTexture('uAtlasN', atlas.normal);
      ms += atlas.bakeMs;
      bytes += 2 * (ATLAS_CELLS * cellPx) ** 2 * 4 * (4 / 3);
    }
    this.stats.bakeMs = ms;
    this.stats.atlasPx = ATLAS_CELLS * cellPx;
    this.stats.atlasBytes = bytes;
  }

  private buildChunks(height: HeightSource, tables: readonly ChunkTable[]): void {
    const g = Math.max(1, Math.floor(this.opts.groupChunks ?? 1));
    const groups = new Map<number, ChunkTable[]>();
    for (const t of tables) {
      if (t.bytes.length % INSTANCE_BYTES !== 0) throw new Error(`vegetation: table (${t.cx},${t.cz}) is not a multiple of ${INSTANCE_BYTES} bytes`);
      const key = Math.floor(t.cz / g) * 100000 + Math.floor(t.cx / g);
      const list = groups.get(key);
      if (list) list.push(t);
      else groups.set(key, [t]);
    }
    for (const [, members] of groups) {
      const first = members[0]!;
      const gx = Math.floor(first.cx / g);
      const gz = Math.floor(first.cz / g);
      const perSpecies: { t: ChunkTable; id: number }[][] = [[], [], [], []];
      for (const t of members) {
        const n = t.bytes.length / INSTANCE_BYTES;
        for (let i = 0; i < n; i++) {
          const sp = t.bytes[i * INSTANCE_BYTES + 3]!;
          if (sp < SPECIES.length) perSpecies[sp]!.push({ t, id: i });
        }
      }
      for (const info of SPECIES) {
        const items = perSpecies[info.id]!;
        if (items.length === 0) continue;
        const gfx = this.gfx[info.id]!;
        const comp = makeCompact(items.length);
        const box: Box = { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity, minZ: Infinity, maxZ: -Infinity };
        items.forEach(({ t, id }, k) => {
          const d = unpackInstance(t.bytes, id * INSTANCE_BYTES);
          const x = t.cx * CHUNK_SIZE_M + d.x;
          const z = t.cz * CHUNK_SIZE_M + d.z;
          const y = height.heightAt(x, z);
          const yaw = rotYaw(d.rotByte);
          comp.pos[k * 3] = x;
          comp.pos[k * 3 + 1] = y;
          comp.pos[k * 3 + 2] = z;
          comp.scale[k] = speciesScale(info, d.scaleByte);
          comp.cos[k] = Math.cos(yaw);
          comp.sin[k] = Math.sin(yaw);
          comp.rank[k] = info.id === SPECIES_GRASS ? hash4(Math.round(d.x * POS_STEPS_PER_M), Math.round(d.z * POS_STEPS_PER_M), t.cx * 64 + t.cz, 77) & 255 : 0;
          box.minX = Math.min(box.minX, x);
          box.maxX = Math.max(box.maxX, x);
          box.minZ = Math.min(box.minZ, z);
          box.maxZ = Math.max(box.maxZ, z);
          box.minY = Math.min(box.minY, y);
          box.maxY = Math.max(box.maxY, y);
        });
        const lodCount = gfx.masters.length;
        const lb = new LodBuckets(comp, lodCount, box);
        const ext = gfx.bounds.radius * info.scaleMax + 1;
        const bb = new BoundingInfo(new Vector3(box.minX - ext, box.minY - 1, box.minZ - ext), new Vector3(box.maxX + ext, box.maxY + (gfx.bounds.maxY + 1) * info.scaleMax, box.maxZ + ext));
        const meshes: Mesh[] = [];
        for (let l = 0; l < lodCount; l++) {
          const m = gfx.masters[l]!.clone(`PH_${info.reqId}__${info.key}_c${gx}_${gz}_${l === lodCount - 1 && lodCount === 3 ? 'imp' : `lod${l}`}`, null, true);
          m.makeGeometryUnique(); // thin-instance buffers are attached to the geometry: clones must not share it
          m.material = gfx.materials[l]!;
          m.setEnabled(false);
          m.thinInstanceSetBuffer('matrix', lb.buffers[l]!, 16, false);
          m.thinInstanceCount = 0;
          m.doNotSyncBoundingInfo = true;
          m.setBoundingInfo(bb);
          m.isPickable = false;
          m.alwaysSelectAsActiveMesh = false;
          m.freezeWorldMatrix();
          meshes.push(m);
          this.meshes.push(m);
          this.stats.bufferBytes += lb.buffers[l]!.byteLength;
        }
        this.buckets.push({ species: info.id, cx: gx, cz: gz, buckets: lb, meshes });
        const key = info.key as 'grass' | 'shrub' | 'tree';
        this.stats.total[key] += items.length;
      }
    }
  }

  // ---------------------------------------------------------------- per frame

  private thresholds(species: number): number[] {
    const q = this.quality;
    if (species === SPECIES_GRASS) return [q.grassDistance * 0.55, q.grassDistance];
    const s = species === SPECIES_SHRUB ? q.shrub : q.tree;
    return [s.lod0, s.lod1, s.far];
  }

  /** Like `update`, but without the CPU budget: use after a camera jump (spawn, teleport) or in tests and screenshots. */
  settle(camera: Camera, dtSec = 0): void {
    const b = this.budgetMs;
    this.budgetMs = Infinity;
    this.update(camera, dtSec);
    this.budgetMs = b;
  }

  private refreshThresholds(): void {
    this.thr2 = [0, 1, 2].map((sp) => this.thresholds(sp).map((t) => t * t));
    this.thrVersion++;
  }

  get qualityTier(): QualityTier {
    return this.quality.name;
  }

  setQuality(tier: QualityTier): void {
    this.quality = QUALITY_M0[tier];
    this.refreshThresholds();
    const q = this.quality;
    const fade = this.gfx[SPECIES_GRASS]!.materials[0]!;
    fade.setVector2('uFade', new Vector2(q.grassDistance * 0.75, q.grassDistance));
    for (const b of this.buckets) b.buckets.invalidate();
  }

  setBudget(ms: number): void {
    this.budgetMs = ms;
  }

  /** Re-bucket instances for `camera` and advance the wind clock by `dtSec`. Call once per frame before rendering. */
  update(camera: Camera, dtSec: number): void {
    const t0 = performance.now();
    camera.getViewMatrix(true); // refresh globalPosition (this runs before the scene renders the frame)
    const p = camera.globalPosition;
    this.wind.time = (this.wind.time + dtSec) % this.windPeriod;
    this.camVec.copyFrom(p);
    windUniform(this.wind, undefined);
    this.windVec.set(this.wind.dirX, this.wind.dirZ, this.wind.strength, this.wind.time);
    for (const m of this.materials) {
      m.setVector3('uCam', this.camVec);
      m.setVector4('uWind', this.windVec);
    }

    const grassLimit = Math.round(this.quality.grassDensity * 256);
    const thr = this.thr2;
    const n = this.buckets.length;
    let moved = 0;
    let deferred = 0;
    let upload = 0;
    const start = n > 0 ? this.rotate % n : 0;
    for (let k = 0; k < n; k++) {
      const b = this.buckets[(start + k) % n]!;
      if (performance.now() - t0 > this.budgetMs) {
        deferred++;
        continue;
      }
      const r = b.buckets.update(p.x, p.y, p.z, thr[b.species]!, this.thrVersion, b.species === SPECIES_GRASS ? grassLimit : 256);
      if (r > 0) moved += r;
      const lb = b.buckets;
      for (let l = 0; l < lb.lodCount; l++) {
        if (!lb.dirty[l]) continue;
        const m = b.meshes[l]!;
        m.thinInstanceCount = lb.counts[l]!;
        const runs = lb.dirtyRuns(l);
        const tu = performance.now();
        if (runs === null) m.thinInstanceBufferUpdated('matrix');
        else for (let r = 0; r < runs.length; r += 2) m.thinInstancePartialBufferUpdate('matrix', lb.buffers[l]!.subarray(runs[r]! * 16, (runs[r]! + runs[r + 1]!) * 16), runs[r]! * 16);
        upload += performance.now() - tu;
        lb.clearDirty(l);
        m.setEnabled(!this.isolated && lb.counts[l]! > 0);
      }
    }
    this.rotate = deferred > 0 ? this.rotate + 1 : 0;
    const dt = performance.now() - t0;
    this.rebucketStats.push(dt);
    this.stats.rebucketMs = dt;
    this.stats.uploadMs = upload;
    this.stats.classifyMs = dt - upload;
    this.classifyStats.push(dt - upload);
    this.stats.deferred = deferred;
    this.stats.moved = moved;
    this.refreshCounts();
  }

  private refreshCounts(): void {
    const s = this.stats.perLod;
    s.grass.fill(0);
    s.shrub.fill(0);
    s.tree.fill(0);
    for (const b of this.buckets) {
      const arr = b.species === SPECIES_GRASS ? s.grass : b.species === SPECIES_SHRUB ? s.shrub : s.tree;
      for (let l = 0; l < b.buckets.lodCount; l++) arr[l]! += b.buckets.counts[l]!;
    }
  }

  /** Draw statistics of the last rendered frame: only meshes that survived frustum culling count. */
  perfStats(): { drawCalls: number; instances: number; tris: number } {
    if (!this.trisOf) {
      this.trisOf = new Map();
      for (const b of this.buckets) b.meshes.forEach((m, l) => this.trisOf!.set(m, this.gfx[b.species]!.tris[l]!));
    }
    const trisOf = this.trisOf;
    let drawCalls = 0;
    let instances = 0;
    let tris = 0;
    const active = this.scene.getActiveMeshes();
    for (let i = 0; i < active.length; i++) {
      const m = active.data[i] as Mesh;
      const t = trisOf.get(m);
      if (t === undefined) continue;
      drawCalls++;
      instances += m.thinInstanceCount;
      tris += t * m.thinInstanceCount;
    }
    this.stats.drawn = { instances, drawCalls, tris };
    return { drawCalls, instances, tris };
  }

  /** Window statistics of the per-frame re-bucketing time (sorts the window: call at most a few times per second). */
  refreshRebucketStats(): WindowStats {
    this.stats.classify = this.classifyStats.stats();
    this.stats.rebucket = this.rebucketStats.stats();
    return this.stats.rebucket;
  }

  overlayLines(): string[] {
    const s = this.stats;
    const now = performance.now();
    if (now - this.lastStatsAt > 250) {
      this.lastStatsAt = now;
      this.refreshRebucketStats();
    }
    const p = this.perfStats();
    const f = (a: number[]) => a.join('/');
    return [
      `veg       inst grass ${s.total.grass} shrub ${s.total.shrub} tree ${s.total.tree}   quality ${this.quality.name}`,
      `  per LOD grass ${f(s.perLod.grass)}  shrub ${f(s.perLod.shrub)}  tree ${f(s.perLod.tree)}  (L0/L1/impostor)`,
      `  drawn ${p.instances} inst  ${p.drawCalls} draws  ${p.tris} tris   rebucket ${s.rebucketMs.toFixed(3)} ms (classify p99 ${s.classify.p99.toFixed(3)}, total p99 ${s.rebucket.p99.toFixed(3)}, defer ${s.deferred})`,
    ];
  }

  // ---------------------------------------------------------------- debug / test hooks

  /**
   * Show a single instance of `species` in the given LOD at (x, y, z) (e2e coverage test) and optionally hide everything
   * else. LOD index: 0, 1 = meshes, 2 = impostor (shrub/tree only).
   */
  probe(species: 'grass' | 'shrub' | 'tree', lod: number, x: number, y: number, z: number, yaw = 0, scale = 1): Mesh {
    const g = this.gfx[species === 'tree' ? SPECIES_TREE : species === 'grass' ? SPECIES_GRASS : SPECIES_SHRUB]!;
    const m = g.masters[lod]!.clone(`PH_${g.info.reqId}__probe_${species}_${lod}`, null, true);
    m.makeGeometryUnique();
    m.material = g.materials[lod]!;
    const comp = makeCompact(1);
    comp.pos.set([x, y, z]);
    comp.scale[0] = scale;
    comp.cos[0] = Math.cos(yaw);
    comp.sin[0] = Math.sin(yaw);
    const buf = new Float32Array(16);
    writeInstanceMatrix(buf, 0, comp, 0);
    m.thinInstanceSetBuffer('matrix', buf, 16, true);
    m.doNotSyncBoundingInfo = true;
    m.alwaysSelectAsActiveMesh = true;
    m.setEnabled(true);
    this.probes.push(m);
    return m;
  }

  /**
   * Render only the current probe meshes through the active camera into a square offscreen target and return the alpha
   * channel (255 where something was drawn). Backend-independent coverage check for e2e (also on WebGPU, where the
   * canvas cannot be read back under the SwiftShader shim): LOD1 mesh and impostor go through the same capture path.
   */
  async captureProbes(size = 256): Promise<{ size: number; alpha: Uint8Array }> {
    const scene = this.scene;
    const rtt = new RenderTargetTexture('PH_V-NAT-000_probe_capture', size, scene, false);
    rtt.clearColor = new Color4(0, 0, 0, 0);
    rtt.activeCamera = scene.activeCamera;
    rtt.renderList = this.probes.slice();
    rtt.refreshRate = RenderTargetTexture.REFRESHRATE_RENDER_ONCE;
    scene.customRenderTargets.push(rtt);
    scene.render();
    scene.customRenderTargets.splice(scene.customRenderTargets.indexOf(rtt), 1);
    const px = (await rtt.readPixels()) as Uint8Array;
    rtt.dispose();
    const alpha = new Uint8Array(size * size);
    for (let i = 0; i < alpha.length; i++) alpha[i] = px[i * 4 + 3]!;
    return { size, alpha };
  }

  clearProbes(): void {
    for (const m of this.probes) m.dispose();
    this.probes = [];
  }

  /** Hide the chunk meshes (probes stay visible); `update` keeps them hidden until called with false. */
  isolate(on: boolean): void {
    this.isolated = on;
    for (const b of this.buckets) {
      b.meshes.forEach((m, l) => m.setEnabled(!on && b.buckets.counts[l]! > 0));
    }
  }

  /** Per-species LOD of every instance currently in the bucket lists (test helper). */
  get bucketList(): readonly Bucket[] {
    return this.buckets;
  }

  get windState(): WindState {
    return this.wind;
  }

  dispose(): void {
    this.clearProbes();
    for (const m of this.meshes) m.dispose(false, false);
    for (const g of this.gfx) for (const m of g.masters) m.dispose(false, false);
    for (const mat of this.materials) mat.dispose();
    for (const a of this.atlases.values()) a.dispose();
    this.meshes.length = 0;
    this.buckets.length = 0;
  }
}
